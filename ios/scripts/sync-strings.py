#!/usr/bin/env python3
"""Build the iOS prototype's .strings tables from the Mac tables plus iOS-only lines.

en:      macos/Resources/Localization/en.lproj/Localizable.strings, then ios/Localization/en.ios.strings
         (a key in the iOS file replaces the Mac value; the Mac file is never edited).
zh-Hans: ios/Localization/zh-Hans.ios.strings (keys are the zh text, so it stays tiny).
Run from anywhere: python3 ios/scripts/sync-strings.py [--check]
"""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
pair = re.compile(r'^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;\s*$')

def entries(path):
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = pair.match(line)
        if m:
            out[m.group(1)] = m.group(2)
    return out

def render(header, table):
    lines = [f"/* {header} */", ""]
    lines += [f'"{k}" = "{v}";' for k, v in table.items()]
    return "\n".join(lines) + "\n"

mac_en = entries(root / "macos/Resources/Localization/en.lproj/Localizable.strings")
ios_en = entries(root / "ios/Localization/en.ios.strings")
en = dict(mac_en)
en.update(ios_en)
zh = entries(root / "ios/Localization/zh-Hans.ios.strings")
gen = "Generated by ios/scripts/sync-strings.py. Edit ios/Localization/*.ios.strings or the Mac table, not this file."
targets = {
    root / "ios/VeerMobile/en.lproj/Localizable.strings": render(gen, en),
    root / "ios/VeerMobile/zh-Hans.lproj/Localizable.strings": render(gen, zh),
}
check = "--check" in sys.argv
stale = []
for path, text in targets.items():
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(str(path.relative_to(root)))
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
if stale:
    sys.exit("stale: " + ", ".join(stale) + " (run python3 ios/scripts/sync-strings.py)")
print(f"en: {len(mac_en)} Mac + {len(ios_en)} iOS ({len(set(mac_en) & set(ios_en))} overridden) = {len(en)}; zh-Hans: {len(zh)}")
